  function w4SpeedFromQuests(done) {              // Best Ore!V63
    if (done >= 23) return 0.2;
    if (done >= 15) return 0.3;
    if (done >= 12) return 0.4;
    if (done >= 7) return 0.5;
    if (done >= 4) return 0.6;
    if (done >= 1) return 0.7;
    return 0.8;
  }

  function w4SpeedFromManual(v) {                 // Best Ore!V30, manual branch
    if (!isNum(v)) return 0.8;
    var m = Math.abs(v);
    return clamp(Math.round((m > 1 ? m / 100 : m) * 10) / 10, 0.2, 0.8);
  }

  function pair(c, m) { return { c: c, m: m }; }

  // Build env from the game's ExportStats (the sheet's "JSON loaded" branch).
  function fromExport(stats, version) {
    var s = stats || {};
    function g(k, d) { var v = s[k]; return isNum(v) ? v : (d === undefined ? 0 : d); }
    function pc(k) { return Math.min(g(k, 0) / 100, 1); }               // K = MIN(J/100, 1)
    function arr(k, i) { var a = s[k]; return Array.isArray(a) ? a[i] : undefined; }
    function flag(k) { return truthy(s[k]); }
    function count(k) {
      var v = s[k];
      if (Array.isArray(v)) return v.filter(function (x) { return truthy(x); }).length;
      return isNum(v) ? v : 0;
    }

    var chance = Math.min(g("void_portal_chance", 0) / 100, 1);           // K3
    var voidFueled = flag("is_drone_void_equipped_and_fueled");           // K50
    var world = g("worlds_unlocked", 1);                                  // K16
    var current = g("current_floor", 0);                                  // K15 / V34
    var w3Fix = arr("fishing_notices_array", 14) === 1;                   // K14
    var w4Mod = w4SpeedFromQuests(g("world_4_quest_progress", 0));        // V63
    var rawSpeed = g("game_speed_multi", 1);                              // K12
    var onFloor = current >= 1 && current <= FLOOR_COUNT ? FLOORS[current - 1] : null;
    // V28: undo the penalties of the floor the export was taken on
    var baseSpeed = rawSpeed /
      ((current >= 73 && current <= 102 && !w3Fix) ? 0.7 : 1) /
      ((current >= 103 && current <= 132) ? 1 - w4Mod : 1) /
      (onFloor ? onFloor.mods.speedX : 1);
    var uptime = arr("item_uptime_array", 25);                            // J19 / J20
    var bombMulti = Math.min(1 + g("bomb_additional_multiplier", 0), 99999); // K72/K85

    var normalMulti = chance === 0 ? 0 : (voidFueled ? g("void_portal_multi", 0) : 1);   // V20, V52

    return {
      jsonLoaded: true,
      version: version || null,
      world: world,
      currentFloor: current,
      goldenFloor: pair(pc("golden_floor_chance"), g("golden_floor_multi", 1)),        // V5, V6
      rainbowFloor: pair(pc("rainbow_floor_chance"), g("rainbow_floor_multi", 1)),     // V7, V8
      galacticFloor: pair(pc("galactic_floor_chance"), g("galactic_floor_multi", 1)),  // V9, V10
      prismaticFloor: pair(pc("prismatic_floor_chance"), g("prismatic_floor_multi", 1)), // V11, V12
      prismaticRaw: g("prismatic_floor_chance", 0) / 100,                              // Floors!Y5
      goldenOre: pair(pc("golden_ore_chance"), g("golden_ore_multi", 1)),              // V13, V14
      rainbowOre: pair(pc("rainbow_ore_chance"), g("rainbow_ore_multi", 1)),           // V15, V16
      oreIncome: g("ore_income_multi", 1),                                             // V17
      oresPerScreen: g("ores_per_screen", 10),                                         // V18
      portal: {
        chance: chance,                                                                // V19
        rawChance: chance < 1 ? chance : (isNum(s.void_portal_chance) ? s.void_portal_chance / 100 : 1), // Floors!Y3
        normalMulti: normalMulti,                                                      // V20
        golden: pair(pc("golden_void_portal_chance"), g("golden_void_portal_multi", 1)),   // V21, V22
        rainbow: pair(pc("rainbow_void_portal_chance"), g("rainbow_void_portal_multi", 1)), // V23, V24
        galactic: pair(pc("galactic_void_portal_chance"), g("galactic_void_portal_multi", 1)), // V25, V26
        baseMulti: g("void_portal_base_multi", 1)                                      // V27
      },
      baseSpeed: baseSpeed,                                                            // V28
      rawSpeed: rawSpeed,                                                              // K12
      w3Fix: w3Fix,                                                                    // V29
      w4Mod: w4Mod,                                                                    // V30
      questsDone: g("world_4_quest_progress", 0),
      drones: {
        void: { owned: arr("drones_suit_owned_array", 7) === 1, equipped: flag("is_drone_void_equipped"),
                fueled: voidFueled, grade: g("void_fuel_grade", 0) },
        minotaur: { owned: arr("drones_suit_owned_array", 10) === 1, equipped: flag("is_drone_minotaur_equipped"),
                    fueled: flag("is_drone_minotaur_equipped_and_fueled"), grade: g("minotaur_fuel_grade", 0) },
        veinseeker: { owned: arr("drones_suit_owned_array", 4) === 1, equipped: flag("is_drone_veinseeker_equipped"),
                      fueled: flag("is_drone_veinseeker_equipped_and_fueled"), grade: g("veinseeker_fuel_grade", 0) }
      },
      steak: { active: isNum(uptime) && uptime > 0, seconds: isNum(uptime) ? uptime : 0, perma: 0.001 * g("steak_eaten", 0) },
      craft: { free: pc("free_craft_chance"), x2: pc("double_craft_chance"), x3: pc("triple_craft_chance"),
               x5: pc("craft_5x_chance"), x10: pc("craft_10x_chance"), x20: pc("craft_20x_chance"),
               x100: pc("craft_100x_chance") },
      bop: { goldChance: pc("bomb_of_plenty_make_gold_chance"), multi: g("bomb_of_plenty_multi", 1) },
      trans: { multi: g("bomb_transmuter_multi", 1), bopChance: pc("bomb_trans_apply_bop_chance") },
      barCostMulti: g("bar_craft_cost_multi", 1),
      veins: {
        spawn: g("vein_spawn_rate_multi", 1), income: g("vein_income_multi", 1),
        golden: pair(pc("golden_vein_chance"), g("golden_vein_multi", 1)),
        rainbow: pair(pc("rainbow_vein_chance"), g("rainbow_vein_multi", 1)),
        gleaming: pair(pc("gleaming_vein_chance"), g("gleaming_vein_multi", 1)),
        researched: count("vein_researched_array"), twoX: count("vein_2x_spawn_array")
      },
      bomb: {                                                                          // JSON!K72:K84
        dmg: g("bomb_damage", 0) * bombMulti,
        critChance: pc("bomb_crit_chance"), critMulti: g("bomb_crit_damage", 1),
        superChance: pc("bomb_super_crit_chance"), superMulti: g("bomb_super_crit_damage", 1),
        ultraChance: pc("bomb_ultra_crit_chance"), ultraMulti: g("bomb_ultra_crit_damage", 1),
        omegaChance: pc("bomb_omega_crit_chance"), omegaMulti: g("bomb_omega_crit_damage", 1)
      }
    };
  }

