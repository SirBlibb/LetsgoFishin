  function floorTypeMix(env) {                    // AA4:AB11
    var V5 = env.goldenFloor.c, V6 = env.goldenFloor.m, V7 = env.rainbowFloor.c, V8 = env.rainbowFloor.m;
    var V9 = env.galacticFloor.c, V10 = env.galacticFloor.m, V11 = env.prismaticFloor.c, V12 = env.prismaticFloor.m;
    var AB4 = env.oreIncome, AB5 = V6 * AB4, AB6 = AB5 * V8, AB7 = AB6 * V10, AB8 = AB7 * V12;
    var AB9 = V8 * AB4, AB10 = AB9 * V10, AB11 = AB10 * V12;
    return [
      { name: "Normal floor", p: (1 - V5) * (1 - V7), m: AB4 },
      { name: "Golden floor", p: V5 * (1 - V7), m: AB5 },
      { name: "Golden Rainbow floor", p: V5 * V7 * (1 - V9), m: AB6 },
      { name: "Golden Rainbow Galactic floor", p: V5 * V7 * V9 * (1 - V11), m: AB7 },
      { name: "Golden Rainbow Galactic Prismatic floor", p: V5 * V7 * V9 * V11, m: AB8 },
      { name: "Rainbow floor", p: (1 - V5) * V7 * (1 - V9), m: AB9 },
      { name: "Rainbow Galactic floor", p: (1 - V5) * V7 * V9 * (1 - V11), m: AB10 },
      { name: "Rainbow Galactic Prismatic floor", p: (1 - V5) * V7 * V9 * V11, m: AB11 }
    ];
  }

  function portalMix(env) {                       // AA15:AB25 (Best Veins!AA4:AB14 is the same maths)
    var p = env.portal;
    var V19 = p.chance;
    var a23 = V19 * p.golden.c * p.rainbow.c * p.galactic.c;
    var a21 = V19 * p.golden.c * p.rainbow.c - a23;
    var a19 = V19 * p.golden.c - (a21 + a23);
    var a17 = V19 - (a19 + a21 + a23);
    var b17 = p.normalMulti * p.baseMulti;
    var b19 = b17 * p.golden.m, b21 = b19 * p.rainbow.m, b23 = b21 * p.galactic.m;
    var rows = [
      { name: "No portal", p: 1 - V19, m: 1 },
      { name: "Normal void", p: a17, m: b17 },
      { name: "Golden void", p: a19, m: b19 },
      { name: "Rainbow void", p: a21, m: b21 },
      { name: "Galactic void", p: a23, m: b23 }
    ];
    var avg = 0;
    rows.forEach(function (r) { avg += r.p * r.m; });
    return {
      rows: rows, average: avg,
      valuePerRock: a17 * b17 + a19 * b19 + a21 * b21 + a23 * b23,          // Floors!Y4
      // Best Veins!V67 -- average multiplier of a portal that actually fired
      averageWhenFired: V19 === 0 ? 0 : (a17 * b17 + a19 * b19 + a21 * b21 + a23 * b23) / V19
    };
  }

  function oreMultis(env) {                       // AB27, AB28, AB30, AB31
    var c = env.goldenOre.c, m = env.goldenOre.m, rc = env.rainbowOre.c, rm = env.rainbowOre.m;
    return {
      golden: (1 - c) + c * m,
      rainbow: (1 - c) + c * m * ((1 - rc) + rc * rm),
      goldenSteak: (1 - c) + c * (m * 3),
      rainbowSteak: (1 - c) + c * (m * 3) * ((1 - rc) + rc * rm)
    };
  }

