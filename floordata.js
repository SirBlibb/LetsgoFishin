  function isNum(v) { return typeof v === "number" && isFinite(v); }
  function clamp(v, lo, hi) { return Math.max(lo, Math.min(hi, v)); }
  function clamp01(v) { return clamp(v, 0, 1); }
  function worldIdx(world) { return clamp(Math.floor(isNum(world) ? world : 1), 1, 4); }
  function worldCap(world) { return WORLD_LAST_FLOOR[worldIdx(world) - 1]; }
  function truthy(v) { return v === true || (isNum(v) && v > 0); }

  // Floors!AX: wiki health notation ("14.59k", "1.05dc") -> number.
  function parseHealth(text) {
    var s = String(text).replace(/,/g, "").trim().toLowerCase();
    var m = /^([0-9.]+)\s*([a-z]*)$/.exec(s);
    if (!m) return NaN;
    var n = parseFloat(m[1]);
    if (!m[2]) return n;
    var at = UNITS.indexOf(m[2]);
    if (at < 0) return NaN;
    return n * Math.pow(1000, at + 1);
  }

  // "v2.2.52" vs "V2.2.20": numeric, so v2.2.9 < v2.2.10 (the sheet compares text).
  function versionParts(v) {
    var m = /(\d+(?:\.\d+)*)/.exec(String(v === null || v === undefined ? "" : v));
    return m ? m[1].split(".").map(function (x) { return parseInt(x, 10); }) : null;
  }
  function compareVersion(a, b) {
    var pa = versionParts(a), pb = versionParts(b);
    if (!pa || !pb) return null;
    var n = Math.max(pa.length, pb.length);
    for (var i = 0; i < n; i++) {
      var x = pa[i] || 0, y = pb[i] || 0;
      if (x !== y) return x < y ? -1 : 1;
    }
    return 0;
  }

  function fixed2(n) { return isNum(n) ? n.toFixed(2) : String(n); }

  function sheetTime(sec) {                       // Best Ore!V96
    var s = Math.round(sec);
    if (!isNum(s)) return "?";
    if (s >= 86400) return Math.floor(s / 86400) + "d " + Math.floor((s % 86400) / 3600) + "h";
    if (s >= 3600) return Math.floor(s / 3600) + "h " + Math.floor((s % 3600) / 60) + "m";
    return Math.floor(s / 60) + "m " + (s % 60) + "s";
  }

