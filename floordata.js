  function evaluateOre(env, opts) {
    opts = opts || {};
    var level = oreLevelOf(opts.ore);               // Floors!Y2
    var ore = level ? ORES[level - 1] : null;
    var showW4 = !!opts.showW4;                     // Best Ore!E7
    var voidMode = opts.voidMode || "auto";

    var mix = floorTypeMix(env);
    var pm = portalMix(env);
    var om = oreMultis(env);
    var Y2 = level, Y4 = pm.valuePerRock;
    var V18 = env.oresPerScreen, V19 = env.portal.chance;
    var perfectBase = FLOORS_PER_HOUR * env.baseSpeed;                       // (AA12*V28)
    var sumMix = 0;
    mix.forEach(function (r) { sumMix += r.p * r.m; });
    var oreBest = Math.max(om.golden, om.rainbow);
    var x34 = V18 * sumMix * oreBest * perfectBase;                          // X34
    var x35 = Y2 > 0 ? V18 * (pm.rows[0].p * pm.rows[0].m + Y4 / Y2) * sumMix * oreBest * perfectBase : null;  // X35

    var rows = FLOORS.map(function (fl) {
      var P = floorMulti(env, fl), Q = floorsPerHour(env, fl), R = voidRatio(env, fl);
      var S = Y2 === 0 ? 0 : (fl.oreA === Y2 ? fl.shareA : 0) + (fl.oreB === Y2 ? fl.shareB : 0);
      var T_ = Y2 === 0 ? 0 : (fl.oreA >= Y2 ? fl.shareA / fl.oreA : 0) + (fl.oreB >= Y2 ? fl.shareB / fl.oreB : 0);
      return {
        floor: fl.floor, world: fl.world, oreA: fl.oreA, oreB: fl.oreB, shareA: fl.shareA, shareB: fl.shareB,
        mods: fl.mods, negative: fl.negative, notes: fl.notes,
        P: P, Q: Q, R: R, S: S, T: T_,
        U: V18 * S * P * Q,                                                  // base value
        V: V18 * ((1 - R * V19) * S + R * Y4 * T_) * P * Q,                  // void value
        oneShot: floorOneShot(env, fl)
      };
    });

    // AA38 / AA42: the sheet lists only 2 floors without the Void Drone, 20 with it
    var cap = Math.min(worldCap(env.world), (showW4 || Y2 > 66) ? 132 : 102);
    var noVoid = topN(rows.filter(function (r) { return r.U > 0; }).map(function (r) {
      return { floor: r.floor, raw: r.U, value: x34 > 0 ? r.U / x34 : null };
    }), 2);
    var withVoid = topN(rows.filter(function (r) { return r.floor <= cap && r.V > 0; }).map(function (r) {
      return { floor: r.floor, raw: r.V, value: x35 > 0 ? r.V / x35 : null };
    }), 20);

    // E11
    var auto;
    if (V19 > 0) {
      auto = (noVoid.length && withVoid.length) ? (noVoid[0].raw >= withVoid[0].raw ? "No" : "Yes") : "";
    } else {
      auto = (env.jsonLoaded ? env.drones.void.owned === true : env.world >= 2) ? "Yes" : "No";
    }
    var useVoid = voidMode === "on" ? true : voidMode === "off" ? false : auto === "Yes";
    var list = useVoid ? withVoid : noVoid;
    var ranking = list.map(function (r, i) {
      var fl = rows[r.floor - 1];
      return { rank: i + 1, floor: r.floor, value: r.value, raw: r.raw, pctVsNext: pctVsNext(list, i),
               oreA: fl.oreA, oreB: fl.oreB, shareA: fl.shareA, shareB: fl.shareB, oneShot: fl.oneShot };
    });

    var advice = bombAdvice(env, ore);

    /* warnings (Best Ore!G4) -- all that apply, in the sheet's order of precedence */
    var warnings = [];
    var ver = env.version ? compareVersion(env.version, SHEET.gameVersion) : null;
    if (env.jsonLoaded) {
      if (ver !== null && ver < 0) {
        warnings.push(note("json-outdated", "warn", "Your imported JSON stats are from an outdated game version (" + env.version +
          "). This spreadsheet requires version " + SHEET.gameVersion + ". Please update your game and import your stats again."));
      }
      if (!ore) {
        warnings.push(note("no-ore", "info", "Select the ore you want to farm."));
      } else {
        var sel = oneShot(env, ore);
        if (sel === false) {
          warnings.push(note("ore-not-oneshot", "danger", "You are unable to oneshot the selected ore 100% of the time"));
        }
        var top5 = ranking.slice(0, 5);
        var bad = top5.filter(function (r) { return !r.oneShot; });
        if (bad.length) {
          warnings.push(note("floors-not-oneshot", "danger", useVoid
            ? "You are unable to oneshot the top 5 floors recommended for your selected ore. The floor results have been expanded to compensate for this."
            : "You are unable to oneshot every ore on the " + top5.length + " floor(s) recommended for your selected ore. Without void portals there are no further floors to list.",
            { floors: bad.map(function (r) { return r.floor; }) }));
        }
      }
      if (ver !== null && ver > 0) {
        warnings.push(note("json-newer", "warn", "Your imported JSON stats are from a newer game version (" + env.version +
          ") than this spreadsheet has been tested against (" + SHEET.gameVersion + "). The spreadsheet may not function correctly—continue at your own risk."));
      }
    }

    /* reminders (Best Ore!G11) */
    var reminders = [];
    if (env.jsonLoaded) {
      var cur = env.currentFloor;
      if (cur >= 1 && cur <= FLOOR_COUNT && FLOORS[cur - 1].negative) {
        reminders.push(note("exported-on-modifier-floor", "warn", "The floor you were on when you exported your stats includes negative ore modifiers.  Please move to a floor with no modifiers, and re-export your stats.", { floor: cur }));
      }
      droneReminders(env, reminders);
      var d = env.drones;
      if (d.minotaur.owned && !d.minotaur.equipped) {
        reminders.push(note("minotaur-not-equipped", "warn", "The Minotaur Drone is unlocked but not equipped. It significantly boosts Void Portals—please equip it and re-import your stats."));
      }
      if (d.minotaur.owned && d.minotaur.equipped && !d.minotaur.fueled) {
        reminders.push(note("minotaur-not-fueled", "warn", "Your Minotaur Drone is not fueled!"));
      }
      if (env.steak) {
        if (!env.steak.active) {
          reminders.push(note("steak-off", "info", "You didn't have 'Golden Steak' active at the time of export.  Your expected Golden Ore multiplier would go from " +
            fixed2(om.golden) + " to " + fixed2(om.goldenSteak) + ".", { from: om.golden, to: om.goldenSteak }));
        } else {
          // V95: remaining time in real seconds (the timer runs at game speed, doubled on floors 107-108)
          var left = env.steak.seconds / (env.rawSpeed * ((env.currentFloor >= 107 && env.currentFloor <= 108) ? 2 : 1));
          if (left < 1800) {
            reminders.push(note("steak-low", "info", "Your 'Golden Steak' had only " + sheetTime(left) + " remaining at the time of export.", { seconds: left }));
          }
        }
      }
    }

    return {
      kind: "ore",
      ore: ore, level: level,
      showW4: showW4, cap: cap,
      rows: rows, mix: mix, portal: pm, oreMultis: om,
      perfect: { base: x34, void: x35 },
      noVoid: noVoid, withVoid: withVoid,
      autoVoid: auto, voidMode: voidMode, useVoid: useVoid,
      ranking: ranking,
      bombAdvice: advice,
      oneShotSelected: ore ? oneShot(env, ore) : null,
      warnings: warnings, reminders: reminders
    };
  }

