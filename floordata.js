  function craftMulti(env) {                      // Best Ore!Y69
    var c = env.craft;
    return (1 / (1 - c.free)) * (1 + Math.min(c.x2, 1) * 1) * (1 + Math.min(c.x3, 1) * 2) *
      (1 + Math.min(c.x5, 1) * 4) * (1 + Math.min(c.x10, 1) * 9) * (1 + Math.min(c.x20, 1) * 19) *
      (1 + Math.min(c.x100, 1) * 99);
  }

  function bombAdvice(env, ore) {                 // Best Ore!Y64:Z71, V49
    if (!env.jsonLoaded || !env.craft || !ore) return null;
    var oc = env.goldenOre, rc = env.rainbowOre;
    var y65 = oc.c * (1 - rc.c), y66 = oc.c * rc.c, y64 = 1 - (y65 + y66);
    var y67 = y64 * 1 + y65 * oc.m + y66 * oc.m * rc.m;
    var gz = oc.c + (1 - oc.c) * env.bop.goldChance;
    var z65 = gz * (1 - rc.c), z66 = gz * rc.c, z64 = 1 - (z65 + z66);
    var z67 = z64 * 1 + z65 * oc.m + z66 * oc.m * rc.m;
    var y69 = craftMulti(env);
    var v36 = ore.baseCost * env.barCostMulti;
    var v45 = env.bop.multi, v46 = env.trans.multi, v47 = env.trans.bopChance;
    var y70 = v45 * y69 / v36 * z67;
    var y71 = v45 * y69 / v36 * (1 - v47) + y67 * v46 * (1 - v47) + v45 * z67 * y69 / v36 * v47 + z67 * v45 * v46 * v47;
    return { bomb: y71 > y70 ? "Transmuter Bomb" : "Bomb of Plenty", bopValue: y70, transValue: y71, craft: y69, barCost: v36 };
  }

