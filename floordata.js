  function floorMulti(env, fl) {                  // Floors!P
    var mods = fl.mods;
    var g = mods.goldenFloor === null ? env.goldenFloor.c : mods.goldenFloor;
    var pz = mods.prismaticDelta === 0 ? env.prismaticFloor.c : clamp(env.prismaticRaw + mods.prismaticDelta, 0, 1);
    var c = env.goldenOre.c, m = env.goldenOre.m, rc = env.rainbowOre.c, rm = env.rainbowOre.m;
    var go = (1 - c) + c * m * mods.goldenOreX;
    var ro = (1 - c) + c * m * mods.goldenOreX * ((1 - rc) + rc * rm);
    return Math.max(go, ro) * env.oreIncome *
      ((1 - g) + g * env.goldenFloor.m) *
      ((1 - env.rainbowFloor.c) + env.rainbowFloor.c * mods.rainbowX * env.rainbowFloor.m *
        ((1 - env.galacticFloor.c) + env.galacticFloor.c * env.galacticFloor.m * ((1 - pz) + pz * env.prismaticFloor.m)));
  }

  function worldSpeedFactor(env, world) {         // Floors!Q (World 3 / World 4 penalties)
    if (world === 3) return env.w3Fix ? 1 : 0.7;
    if (world === 4) return isNum(1 - env.w4Mod) ? 1 - env.w4Mod : 1;
    return 1;
  }

  function floorsPerHour(env, fl) {               // Floors!Q  (= Best Veins!AF without the vein constant)
    return FLOORS_PER_HOUR * env.baseSpeed * fl.mods.speedX * worldSpeedFactor(env, fl.world);
  }

  function voidRatio(env, fl) {                   // Floors!R
    if (env.portal.chance <= 0) return 1;
    return Math.min(fl.mods.portalX * env.portal.rawChance, 1) / env.portal.chance;
  }

  // Floors!AY -- can one bomb kill the ore 100% of the time?
  // (The sheet's own cells show #VALUE! when no tier is enough, and IFERROR then
  // reads that as "yes"; we report the real answer.  null = no bomb stats.)
  function oneShot(env, ore) {
    var b = env.bomb;
    if (!b || !ore) return null;
    var tier = ore.critTier ? TIER_INDEX[ore.critTier] : 0;
    if (tier === 1 && b.superChance < 1) return false;
    if (tier === 2 && b.ultraChance < 1) return false;
    if (tier === 3 && b.omegaChance < 1) return false;
    var bd = b.dmg - b.dmg * ore.damageReduction;
    var bdc = bd * b.critMulti, bds = bdc * b.superMulti, bdu = bds * b.ultraMulti, bdo = bdu * b.omegaMulti;
    var hp = ore.health;
    if (bd > hp) return true;
    if (b.critChance >= 1 && bdc > hp) return true;
    if (b.superChance >= 1 && bds > hp) return true;
    if (b.ultraChance >= 1 && bdu > hp) return true;
    if (b.omegaChance >= 1 && bdo > hp) return true;
    return false;
  }

  function floorOneShot(env, fl) {                // Floors!W
    var a = oneShot(env, ORES[fl.oreA - 1]), b = oneShot(env, ORES[fl.oreB - 1]);
    if (a === null || b === null) return true;
    return a && b;
  }

