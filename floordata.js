        (fl.world === 3 ? (env.w3Fix ? 1 : 0.7) : 1) * (fl.world === 4 ? (isNum(1 - env.w4Mod) ? 1 - env.w4Mod : 1) : 1);
      var AG = (fl.floor >= V54 && fl.floor <= V55) ? 1 : 0;
