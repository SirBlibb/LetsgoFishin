  // SORTN(FILTER(...), n, 0, 2, FALSE, 1, TRUE): value descending, floor ascending.
  function topN(items, n) {
    return items.slice().sort(function (a, b) {
      if (b.raw !== a.raw) return b.raw - a.raw;
      return a.floor - b.floor;
    }).slice(0, n);
  }

  function pctVsNext(list, i) {
    if (i + 1 >= list.length) return null;
    var cur = list[i].value, next = list[i + 1].value;
    if (!isNum(cur) || !isNum(next) || next === 0) return null;
    return cur / next - 1;
  }

