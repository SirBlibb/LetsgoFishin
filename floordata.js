  function fromManual(input) {
    var m = {};
    var d = defaultManual();
    Object.keys(d).forEach(function (k) {
      var v = input ? input[k] : undefined;
      m[k] = typeof d[k] === "boolean" ? !!v : (isNum(v) ? v : d[k]);
    });
    function frac(pct) { return clamp01(pct / 100); }
    var world = worldIdx(m.world);                                         // V31 = I19
    var w = function (min, v) { return world >= min ? v : 0; };

    var portalFrac = frac(m.portalChance);                                 // M5
    var chance = (world >= 2 && m.voidEquipped) ? portalFrac : 0;          // V19
    var mino = (world >= 4 && m.minoEquipped && m.minoFueled) ? 0.0025 + m.minoGrade * 0.0025 : 0;  // V65
    var multi = 0;                                                         // V20
    if (m.voidEquipped) {
      multi = m.voidFueled
        ? (3 + m.voidGrade) * (1 + mino) * (1 + w(4, m.coalLevel * 0.005)) * (1 + w(4, m.lvl400 * 0.001)) *
          (1 + (world >= 4 && m.omni ? 0.02 : 0)) * (1 + w(4, m.contractLevel * 0.004)) *
          (1 + w(4, m.arcanist * 0.005)) * (1 + w(4, m.hydra * 0.0075))
        : 1;
    }

    return {
      jsonLoaded: false,
      version: null,
      world: world,
      currentFloor: null,
      goldenFloor: pair(frac(m.goldenFloorChance), m.goldenFloorMulti),                              // V5 / V6
      rainbowFloor: pair(world >= 2 ? frac(m.rainbowFloorChance) : 0, m.rainbowFloorMulti),          // V7 / V8
      galacticFloor: pair(world >= 3 ? frac(m.galacticFloorChance) : 0, m.galacticFloorMulti),       // V9 / V10
      prismaticFloor: pair(world >= 4 ? frac(m.prismaticFloorChance) : 0, m.prismaticFloorMulti),     // V11 / V12
      prismaticRaw: m.prismaticFloorChance / 100,                                                     // Floors!Y5 = P17
      goldenOre: pair(world >= 3 ? frac(m.goldenOreChance) : 0, m.goldenOreMulti),                    // V13 / V14
      rainbowOre: pair(world >= 4 ? frac(m.rainbowOreChance) : 0, m.rainbowOreMulti),                 // V15 / V16
      oreIncome: m.oreIncome,
      oresPerScreen: m.oresPerScreen,
      portal: {
        chance: chance,
        rawChance: chance < 1 ? chance : Math.max(m.portalChance / 100, 1),                           // Floors!Y3
        normalMulti: multi,
        golden: pair(world >= 3 ? frac(m.goldenPortalChance) : 0, m.goldenPortalMulti),
        rainbow: pair(world >= 3 ? frac(m.rainbowPortalChance) : 0, m.rainbowPortalMulti),
        galactic: pair(world >= 4 ? frac(m.galacticPortalChance) : 0, m.galacticPortalMulti),
        baseMulti: m.portalBase
      },
      baseSpeed: m.gameSpeed,                                                                          // V28 = I35
      rawSpeed: m.gameSpeed,
      w3Fix: !!m.w3Fix,
      w4Mod: w4SpeedFromManual(m.w4Mod),
      questsDone: null,
      drones: {
        void: { owned: null, equipped: m.voidEquipped, fueled: m.voidFueled, grade: m.voidGrade },
        minotaur: { owned: null, equipped: m.minoEquipped, fueled: m.minoFueled, grade: m.minoGrade },
        veinseeker: { owned: null, equipped: null, fueled: null, grade: 0 }
      },
      steak: null, craft: null, bop: null, trans: null, barCostMulti: null,
      veins: {
        spawn: m.veinSpawn, income: m.veinIncome,
        golden: pair(frac(m.goldenVeinChance), m.goldenVeinMulti),
        rainbow: pair(frac(m.rainbowVeinChance), m.rainbowVeinMulti),
        gleaming: pair(frac(m.gleamingVeinChance), m.gleamingVeinMulti),
        researched: null, twoX: null
      },
      bomb: null
    };
  }

