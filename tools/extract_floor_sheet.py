#!/usr/bin/env python3
"""
Dev-only extractor for the "IOM - Best Floor To Farm" Google Sheet (V3.4.2).

Reads an .xlsx export of the workbook (File > Download > Microsoft Excel) and
writes the static data + golden fixtures used by the Best Floor tool:

  floortables.js                  ORES / VEINS / floor-modifier tables (generated)
  test/ref_floors_<name>.json     cached cell values (Floors, Best Ore, Best Veins)
  test/fixtures/export_*.json     the ExportStats JSON pasted into JSON!A5 (if any)
  img/veins/<slug>.png            the 21 vein pictures from the hidden Images tab

Usage (needs `pip install openpyxl`; never fetches anything):
  python3 -I tools/extract_floor_sheet.py tables  loaded.xlsx
  python3 -I tools/extract_floor_sheet.py fixture loaded.xlsx sample
  python3 -I tools/extract_floor_sheet.py fixture default.xlsx default
  python3 -I tools/extract_floor_sheet.py export  loaded.xlsx
  python3 -I tools/extract_floor_sheet.py images  loaded.xlsx

Fixtures hold the sheet's *cached* values, so the xlsx must be exported from a
Sheet that has finished calculating.  Formulas themselves are transcribed by
hand into floordata.js (cell references are kept in comments there).
"""
import json, os, re, sys

try:
    import openpyxl
except ImportError:
    sys.exit("openpyxl is required: pip install openpyxl")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def num(v):
    if isinstance(v, bool) or v is None:
        return v
    if isinstance(v, (int, float)):
        return int(v) if float(v).is_integer() and abs(v) < 1e15 else v
    return v


def tables(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb["Floors"]
    chg = wb["Changelog"]
    sheet = {"version": str(chg["C2"].value), "gameVersion": str(chg["A2"].value)}
    ores = []
    world = 0
    for r in range(2, 88):
        if ws.cell(r, 47).value is None:
            continue
        w = ws.cell(r, 46).value
        if w is not None:
            world = int(w)
        ores.append({
            "level": len(ores) + 1,
            "world": world,
            "name": ws.cell(r, 47).value,
            "baseCost": num(ws.cell(r, 48).value),
            "healthText": str(ws.cell(r, 49).value),
            "health": ws.cell(r, 50).value,
            "damageReduction": ws.cell(r, 52).value or 0,
            "critTier": ws.cell(r, 53).value,
        })
    # the world column only holds the first row of each world (merged cells)
    veins = []
    for r in range(2, 23):
        n = ws.cell(r, 37).value
        if not n:
            continue
        veins.append({
            "index": len(veins) + 1,
            "name": n,
            "firstFloor": int(ws.cell(r, 38).value),
            "lastFloor": int(ws.cell(r, 39).value),
            "rarity": int(ws.cell(r, 40).value),
            "firstOre": int(ws.cell(r, 41).value),
            "lastOre": int(ws.cell(r, 42).value),
            "image": "img/veins/" + slug(n) + ".png",
        })
    mods = []
    for r in range(2, 61):
        f = ws.cell(r, 27).value
        if f is None:
            continue
        m = {"from": int(f), "to": int(ws.cell(r, 28).value)}
        for col, key in ((29, "goldenFloor"), (30, "rainbowX"), (31, "goldenOreX"),
                         (32, "prismaticDelta"), (33, "portalX"), (34, "speedX")):
            v = ws.cell(r, col).value
            if v is not None and v != "":
                m[key] = v
        m["note"] = ws.cell(r, 35).value or ""
        mods.append(m)
    out = ("/* GENERATED by tools/extract_floor_sheet.py from the \"IOM - Best Floor To Farm\"\n"
           " * sheet (Floors tab).  Do not edit by hand - re-run the extractor. */\n"
           "window.FloorTables = " + json.dumps({"sheet": sheet, "ores": ores, "veins": veins, "mods": mods},
                                                 indent=1, ensure_ascii=False) + ";\n")
    with open(os.path.join(ROOT, "floortables.js"), "w", encoding="utf-8") as f:
        f.write(out)
    print("floortables.js:", len(ores), "ores,", len(veins), "veins,", len(mods), "modifier ranges", sheet)


def cell_dump(ws, rows, cols):
    d = {}
    for r in range(rows[0], rows[1] + 1):
        for c in range(cols[0], cols[1] + 1):
            v = ws.cell(r, c).value
            if v is None:
                continue
            d[ws.cell(r, c).coordinate] = num(v) if not isinstance(v, str) else v
    return d


def fixture(path, name):
    wb = openpyxl.load_workbook(path, data_only=True)
    ref = {
        "source": os.path.basename(path),
        "floors": cell_dump(wb["Floors"], (1, 133), (1, 25)),
        "floorsOres": cell_dump(wb["Floors"], (1, 87), (46, 53)),
        "bestOre": cell_dump(wb["Best Ore"], (1, 110), (2, 31)),
        "bestVeins": cell_dump(wb["Best Veins"], (1, 133), (2, 39)),
        "json": cell_dump(wb["JSON"], (1, 100), (9, 11)),
    }
    p = os.path.join(ROOT, "test", "ref_floors_%s.json" % name)
    with open(p, "w", encoding="utf-8") as f:
        json.dump(ref, f, separators=(",", ":"))
    print(p, os.path.getsize(p), "bytes")


def export(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    raw = wb["JSON"]["A5"].value
    if not raw:
        sys.exit("JSON!A5 is empty")
    d = json.loads(raw)
    p = os.path.join(ROOT, "test", "fixtures", "export_%s.json" % d["version"].lstrip("v"))
    with open(p, "w", encoding="utf-8") as f:
        f.write(raw)
    print(p, d["version"], len(d["stats"]), "stats")


def images(path):
    wb = openpyxl.load_workbook(path)
    ws = wb["Images"]
    names = {}
    for r in range(1, 25):
        n = ws.cell(r, 2).value
        if n:
            names[r - 1] = n
    os.makedirs(os.path.join(ROOT, "img", "veins"), exist_ok=True)
    for im in ws._images:
        row = im.anchor._from.row
        if row not in names:
            continue
        data = im._data()
        p = os.path.join(ROOT, "img", "veins", slug(names[row]) + ".png")
        with open(p, "wb") as f:
            f.write(data)
        print(p, len(data))


if __name__ == "__main__":
    a = sys.argv[1:]
    if len(a) >= 2 and a[0] == "tables":
        tables(a[1])
    elif len(a) >= 3 and a[0] == "fixture":
        fixture(a[1], a[2])
    elif len(a) >= 2 and a[0] == "export":
        export(a[1])
    elif len(a) >= 2 and a[0] == "images":
        images(a[1])
    else:
        print(__doc__)
